export const dictionaries: Record<Lang, Dict> = { en, ru, uk };
export type Key = keyof Dict;

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem("crew.lang");
    if (saved === "en" || saved === "ru" || saved === "uk") return saved;
  } catch {}
  const nav = navigator.language.slice(0, 2);
  return nav === "ru" ? "ru" : nav === "uk" ? "uk" : "en";
}

export function translator(lang: Lang) {
  return (key: Key, vars?: Record<string, string>) =>
    dictionaries[lang][key].replace(/\{(\w+)\}/g, (_, k) => vars?.[k] ?? `{${k}}`);
}

export const I18n = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: ReturnType<typeof translator> }>({
  lang: "en",
  setLang: () => {},
  t: translator("en"),
});

export const useT = () => useContext(I18n);
